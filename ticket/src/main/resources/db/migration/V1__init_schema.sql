CREATE TABLE membership_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,

    price NUMERIC(12,2) NOT NULL DEFAULT 0,
    duration_days INT NOT NULL,
    discount_percent NUMERIC(5,2) NOT NULL DEFAULT 0,

    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_membership_plans_name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_membership_plans_price_non_negative CHECK (price >= 0),
    CONSTRAINT ck_membership_plans_duration_positive CHECK (duration_days > 0),
    CONSTRAINT ck_membership_plans_discount_range CHECK (discount_percent >= 0 AND discount_percent <= 100)
);

CREATE INDEX idx_membership_plans_is_active ON membership_plans(is_active);

CREATE TABLE user_memberships (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL,
    plan_id BIGINT NOT NULL,

    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,

    status membership_status NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_user_memberships_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,

    CONSTRAINT fk_user_memberships_plan
        FOREIGN KEY (plan_id) REFERENCES membership_plans(id),

    CONSTRAINT ck_user_memberships_time_valid CHECK (end_at > start_at)
);

CREATE INDEX idx_user_memberships_user_id ON user_memberships(user_id);
CREATE INDEX idx_user_memberships_plan_id ON user_memberships(plan_id);
CREATE INDEX idx_user_memberships_status ON user_memberships(status);
CREATE INDEX idx_user_memberships_end_at ON user_memberships(end_at);
CREATE INDEX idx_user_memberships_user_status ON user_memberships(user_id, status);

-- Optional business rule:
-- Keep this index if the system allows only one ACTIVE membership per user at a time.
-- If you want users to hold multiple ACTIVE memberships, remove this index.
CREATE UNIQUE INDEX ux_user_memberships_one_active_per_user
ON user_memberships(user_id)
WHERE status = 'ACTIVE';

-- =========================================================
-- VOUCHER
-- =========================================================

CREATE TABLE vouchers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    code VARCHAR(50) NOT NULL UNIQUE,
    description TEXT,

    discount_type discount_type NOT NULL,
    discount_value NUMERIC(12,2) NOT NULL,

    max_discount NUMERIC(12,2),
    min_order_amount NUMERIC(12,2) NOT NULL DEFAULT 0,

    membership_required BOOLEAN NOT NULL DEFAULT false,

    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,

    usage_limit INT,
    used_count INT NOT NULL DEFAULT 0,

    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_vouchers_code_not_blank CHECK (length(trim(code)) > 0),
    CONSTRAINT ck_vouchers_time_valid CHECK (end_at > start_at),
    CONSTRAINT ck_vouchers_discount_value_positive CHECK (discount_value > 0),
    CONSTRAINT ck_vouchers_max_discount_non_negative CHECK (max_discount IS NULL OR max_discount >= 0),
    CONSTRAINT ck_vouchers_min_order_non_negative CHECK (min_order_amount >= 0),
    CONSTRAINT ck_vouchers_usage_limit_positive CHECK (usage_limit IS NULL OR usage_limit > 0),
    CONSTRAINT ck_vouchers_used_count_non_negative CHECK (used_count >= 0),
    CONSTRAINT ck_vouchers_used_count_not_exceed_limit CHECK (
        usage_limit IS NULL OR used_count <= usage_limit
    )
);

CREATE INDEX idx_vouchers_code ON vouchers(code);
CREATE INDEX idx_vouchers_is_active ON vouchers(is_active);
CREATE INDEX idx_vouchers_start_at ON vouchers(start_at);
CREATE INDEX idx_vouchers_end_at ON vouchers(end_at);
CREATE INDEX idx_vouchers_membership_required ON vouchers(membership_required);

-- =========================================================
-- ORDER + TICKET
-- =========================================================

CREATE TABLE orders (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    user_id UUID NOT NULL,
    event_id UUID NOT NULL,

    status order_status NOT NULL DEFAULT 'PENDING',

    subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(12,2) NOT NULL DEFAULT 0,

    voucher_id UUID,

    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    paid_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,

    CONSTRAINT fk_orders_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT fk_orders_event
        FOREIGN KEY (event_id) REFERENCES events(id),

    CONSTRAINT fk_orders_voucher
        FOREIGN KEY (voucher_id) REFERENCES vouchers(id),

    CONSTRAINT ck_orders_amounts_non_negative CHECK (
        subtotal >= 0
        AND discount_amount >= 0
        AND total_amount >= 0
    ),
    CONSTRAINT ck_orders_total_valid CHECK (total_amount = subtotal - discount_amount),
    CONSTRAINT ck_orders_discount_not_exceed_subtotal CHECK (discount_amount <= subtotal),
    CONSTRAINT ck_orders_paid_at_required CHECK (
        status <> 'PAID' OR paid_at IS NOT NULL
    ),
    CONSTRAINT ck_orders_cancelled_at_required CHECK (
        status <> 'CANCELLED' OR cancelled_at IS NOT NULL
    )
);

CREATE INDEX idx_orders_user_id ON orders(user_id);
CREATE INDEX idx_orders_event_id ON orders(event_id);
CREATE INDEX idx_orders_status ON orders(status);
CREATE INDEX idx_orders_expires_at ON orders(expires_at);
CREATE INDEX idx_orders_voucher_id ON orders(voucher_id);
CREATE INDEX idx_orders_user_status ON orders(user_id, status);
CREATE INDEX idx_orders_event_status ON orders(event_id, status);

-- Useful for scheduler that expires pending orders.
CREATE INDEX idx_orders_pending_expires
ON orders(expires_at)
WHERE status = 'PENDING';

CREATE TABLE order_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    order_id UUID NOT NULL,
    event_seat_id UUID NOT NULL,

    price_snapshot NUMERIC(12,2) NOT NULL,

    qr_code VARCHAR(255) UNIQUE,
    ticket_status ticket_status NOT NULL DEFAULT 'NOT_ISSUED',

    issued_at TIMESTAMPTZ,
    checked_in_at TIMESTAMPTZ,

    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,

    CONSTRAINT fk_order_items_event_seat
        FOREIGN KEY (event_seat_id) REFERENCES event_seats(id),

    CONSTRAINT uq_order_items_order_event_seat UNIQUE (order_id, event_seat_id),

    CONSTRAINT ck_order_items_price_non_negative CHECK (price_snapshot >= 0),
    CONSTRAINT ck_order_items_ticket_qr_consistency CHECK (
        (
            ticket_status = 'NOT_ISSUED'
            AND qr_code IS NULL
            AND issued_at IS NULL
            AND checked_in_at IS NULL
        )
        OR
        (
            ticket_status IN ('VALID', 'USED', 'CANCELLED')
            AND qr_code IS NOT NULL
            AND issued_at IS NOT NULL
        )
    ),
    CONSTRAINT ck_order_items_used_checked_in CHECK (
        ticket_status <> 'USED' OR checked_in_at IS NOT NULL
    )
);

CREATE INDEX idx_order_items_order_id ON order_items(order_id);
CREATE INDEX idx_order_items_event_seat_id ON order_items(event_seat_id);
CREATE INDEX idx_order_items_ticket_status ON order_items(ticket_status);
CREATE INDEX idx_order_items_qr_code ON order_items(qr_code);

-- A sold/valid ticket should not be duplicated for the same event seat.
-- This still allows old NOT_ISSUED items from expired/cancelled orders.
CREATE UNIQUE INDEX ux_order_items_one_issued_ticket_per_event_seat
ON order_items(event_seat_id)
WHERE ticket_status IN ('VALID', 'USED');

-- =========================================================
-- VOUCHER REDEMPTION
-- =========================================================

CREATE TABLE voucher_redemptions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    voucher_id UUID NOT NULL,
    user_id UUID NOT NULL,
    order_id UUID NOT NULL,

    discount_amount NUMERIC(12,2) NOT NULL,
    used_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_voucher_redemptions_voucher
        FOREIGN KEY (voucher_id) REFERENCES vouchers(id),

    CONSTRAINT fk_voucher_redemptions_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT fk_voucher_redemptions_order
        FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,

    CONSTRAINT uq_voucher_redemptions_voucher_user UNIQUE (voucher_id, user_id),
    CONSTRAINT uq_voucher_redemptions_voucher_order UNIQUE (voucher_id, order_id),

    CONSTRAINT ck_voucher_redemptions_discount_non_negative CHECK (discount_amount >= 0)
);

CREATE INDEX idx_voucher_redemptions_voucher_id ON voucher_redemptions(voucher_id);
CREATE INDEX idx_voucher_redemptions_user_id ON voucher_redemptions(user_id);
CREATE INDEX idx_voucher_redemptions_order_id ON voucher_redemptions(order_id);

-- =========================================================
-- COMMENTS
-- =========================================================

COMMENT ON TABLE users IS 'User account, profile, role and OAuth identity in one table for MVP simplicity.';
COMMENT ON TABLE categories IS 'Event categories. Each event belongs to one category in the simplified model.';
COMMENT ON TABLE events IS 'Movies/showtimes created by providers and managed by admins.';
COMMENT ON TABLE event_sections IS 'Seat sections for each event, such as VIP, A, B.';
COMMENT ON TABLE event_seats IS 'Core booking table. Seat status is managed here with transaction and row locking.';
COMMENT ON TABLE orders IS 'Mock checkout order. PENDING orders hold seats; PAID orders issue tickets.';
COMMENT ON TABLE order_items IS 'Order lines and ticket QR data. One item represents one booked event seat.';
COMMENT ON TABLE membership_plans IS 'Membership packages.';
COMMENT ON TABLE user_memberships IS 'User membership subscription history.';
COMMENT ON TABLE vouchers IS 'Voucher definition and usage counter.';
COMMENT ON TABLE voucher_redemptions IS 'Voucher usage history per user/order.';
