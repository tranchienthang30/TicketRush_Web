-- V1__init_schema.sql
-- TicketRush - Initial PostgreSQL schema
-- Flyway location: src/main/resources/db/migration/V1__init_schema.sql
--
-- Notes:
-- - PostgreSQL is the source of truth.
-- - Redis is used outside this schema for cache, queue, pub/sub, token/rate limit.
-- - Payments are mocked through orders.status = 'PAID'.
-- - Tickets are represented by order_items.qr_code and order_items.ticket_status.

-- =========================================================
-- EXTENSIONS
-- =========================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Optional but useful for event search with ILIKE/fuzzy search later.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- =========================================================
-- ENUM TYPES
-- =========================================================

CREATE TYPE user_role AS ENUM (
    'CUSTOMER',
    'PROVIDER',
    'ADMIN'
);

CREATE TYPE user_status AS ENUM (
    'ACTIVE',
    'BLOCKED'
);

CREATE TYPE auth_provider AS ENUM (
    'LOCAL',
    'GOOGLE'
);

CREATE TYPE event_status AS ENUM (
    'DRAFT',
    'PUBLISHED',
    'CANCELLED',
    'FINISHED'
);

CREATE TYPE seat_status AS ENUM (
    'AVAILABLE',
    'LOCKED',
    'SOLD'
);

CREATE TYPE order_status AS ENUM (
    'PENDING',
    'PAID',
    'EXPIRED',
    'CANCELLED'
);

CREATE TYPE ticket_status AS ENUM (
    'NOT_ISSUED',
    'VALID',
    'USED',
    'CANCELLED'
);

CREATE TYPE discount_type AS ENUM (
    'PERCENT',
    'FIXED'
);

CREATE TYPE membership_status AS ENUM (
    'ACTIVE',
    'EXPIRED',
    'CANCELLED'
);

-- =========================================================
-- COMMON UPDATED_AT TRIGGER
-- =========================================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =========================================================
-- USERS
-- =========================================================

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255),

    full_name VARCHAR(255) NOT NULL,
    avatar_url TEXT,
    phone VARCHAR(30),
    gender VARCHAR(20),
    date_of_birth DATE,

    role user_role NOT NULL DEFAULT 'CUSTOMER',
    status user_status NOT NULL DEFAULT 'ACTIVE',

    provider auth_provider NOT NULL DEFAULT 'LOCAL',
    provider_id VARCHAR(255),

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_users_email_not_blank CHECK (length(trim(email)) > 0),
    CONSTRAINT ck_users_full_name_not_blank CHECK (length(trim(full_name)) > 0),
    CONSTRAINT ck_users_local_password CHECK (
        provider <> 'LOCAL'
        OR password_hash IS NOT NULL
    )
);

CREATE UNIQUE INDEX ux_users_provider_provider_id
ON users(provider, provider_id)
WHERE provider_id IS NOT NULL;

CREATE INDEX idx_users_email ON users(email);
CREATE INDEX idx_users_role ON users(role);
CREATE INDEX idx_users_status ON users(status);

CREATE TRIGGER trg_users_set_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

-- =========================================================
-- CATEGORY, EVENT
-- =========================================================

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(120) NOT NULL UNIQUE,
    description TEXT,
    image_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT true,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_categories_name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_categories_slug_not_blank CHECK (length(trim(slug)) > 0)
);

CREATE INDEX idx_categories_slug ON categories(slug);
CREATE INDEX idx_categories_is_active ON categories(is_active);

CREATE TABLE events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    provider_id UUID NOT NULL,
    category_id BIGINT NOT NULL,

    title VARCHAR(255) NOT NULL,
    slug VARCHAR(300) NOT NULL UNIQUE,
    description TEXT,
    banner_url TEXT,

    location_name VARCHAR(255),
    address TEXT,
    city VARCHAR(100),

    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,

    sale_start_time TIMESTAMPTZ,
    sale_end_time TIMESTAMPTZ,

    status event_status NOT NULL DEFAULT 'DRAFT',

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_events_provider
        FOREIGN KEY (provider_id) REFERENCES users(id),

    CONSTRAINT fk_events_category
        FOREIGN KEY (category_id) REFERENCES categories(id),

    CONSTRAINT ck_events_title_not_blank CHECK (length(trim(title)) > 0),
    CONSTRAINT ck_events_slug_not_blank CHECK (length(trim(slug)) > 0),
    CONSTRAINT ck_events_time_valid CHECK (end_time > start_time),
    CONSTRAINT ck_events_sale_time_valid CHECK (
        sale_start_time IS NULL
        OR sale_end_time IS NULL
        OR sale_end_time > sale_start_time
    )
);

CREATE INDEX idx_events_provider_id ON events(provider_id);
CREATE INDEX idx_events_category_id ON events(category_id);
CREATE INDEX idx_events_slug ON events(slug);
CREATE INDEX idx_events_status ON events(status);
CREATE INDEX idx_events_city ON events(city);
CREATE INDEX idx_events_start_time ON events(start_time);
CREATE INDEX idx_events_status_start_time ON events(status, start_time);
CREATE INDEX idx_events_category_status ON events(category_id, status);
CREATE INDEX idx_events_provider_status ON events(provider_id, status);

-- Useful for header search / event search.
CREATE INDEX idx_events_title_trgm
ON events
USING GIN (title gin_trgm_ops);

CREATE INDEX idx_events_search_vector
ON events
USING GIN (
    to_tsvector(
        'simple',
        coalesce(title, '') || ' ' ||
        coalesce(description, '') || ' ' ||
        coalesce(city, '') || ' ' ||
        coalesce(location_name, '')
    )
);

CREATE TRIGGER trg_events_set_updated_at
BEFORE UPDATE ON events
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

-- =========================================================
-- EVENT SEAT MAP
-- =========================================================

CREATE TABLE event_sections (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    event_id UUID NOT NULL,

    name VARCHAR(100) NOT NULL,
    base_price NUMERIC(12,2) NOT NULL,

    row_count INT NOT NULL,
    seats_per_row INT NOT NULL,

    display_order INT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_event_sections_event
        FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,

    CONSTRAINT uq_event_sections_event_name UNIQUE (event_id, name),

    CONSTRAINT ck_event_sections_name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_event_sections_base_price_non_negative CHECK (base_price >= 0),
    CONSTRAINT ck_event_sections_row_count_positive CHECK (row_count > 0),
    CONSTRAINT ck_event_sections_seats_per_row_positive CHECK (seats_per_row > 0),
    CONSTRAINT ck_event_sections_display_order_non_negative CHECK (display_order >= 0)
);

CREATE INDEX idx_event_sections_event_id ON event_sections(event_id);
CREATE INDEX idx_event_sections_display_order ON event_sections(display_order);

CREATE TRIGGER trg_event_sections_set_updated_at
BEFORE UPDATE ON event_sections
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TABLE event_seats (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    event_id UUID NOT NULL,
    section_id UUID NOT NULL,

    row_label VARCHAR(10) NOT NULL,
    seat_number INT NOT NULL,
    seat_code VARCHAR(40) NOT NULL,

    price NUMERIC(12,2) NOT NULL,

    status seat_status NOT NULL DEFAULT 'AVAILABLE',

    locked_by UUID,
    lock_expires_at TIMESTAMPTZ,

    version INT NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_event_seats_event
        FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,

    CONSTRAINT fk_event_seats_section
        FOREIGN KEY (section_id) REFERENCES event_sections(id) ON DELETE CASCADE,

    CONSTRAINT fk_event_seats_locked_by
        FOREIGN KEY (locked_by) REFERENCES users(id),

    CONSTRAINT uq_event_seats_event_seat_code UNIQUE (event_id, seat_code),
    CONSTRAINT uq_event_seats_event_section_row_seat UNIQUE (event_id, section_id, row_label, seat_number),

    CONSTRAINT ck_event_seats_row_label_not_blank CHECK (length(trim(row_label)) > 0),
    CONSTRAINT ck_event_seats_seat_code_not_blank CHECK (length(trim(seat_code)) > 0),
    CONSTRAINT ck_event_seats_seat_number_positive CHECK (seat_number > 0),
    CONSTRAINT ck_event_seats_price_non_negative CHECK (price >= 0),
    CONSTRAINT ck_event_seats_version_non_negative CHECK (version >= 0),
    CONSTRAINT ck_event_seats_lock_consistency CHECK (
        (
            status = 'LOCKED'
            AND locked_by IS NOT NULL
            AND lock_expires_at IS NOT NULL
        )
        OR
        (
            status <> 'LOCKED'
            AND lock_expires_at IS NULL
        )
    )
);

CREATE INDEX idx_event_seats_event_id ON event_seats(event_id);
CREATE INDEX idx_event_seats_section_id ON event_seats(section_id);
CREATE INDEX idx_event_seats_status ON event_seats(status);
CREATE INDEX idx_event_seats_locked_by ON event_seats(locked_by);
CREATE INDEX idx_event_seats_lock_expires_at ON event_seats(lock_expires_at);
CREATE INDEX idx_event_seats_event_status ON event_seats(event_id, status);
CREATE INDEX idx_event_seats_event_section_status ON event_seats(event_id, section_id, status);

-- Important for the scheduler that releases expired locked seats.
CREATE INDEX idx_event_seats_expired_locks
ON event_seats(lock_expires_at)
WHERE status = 'LOCKED';

CREATE TRIGGER trg_event_seats_set_updated_at
BEFORE UPDATE ON event_seats
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

